if (import.meta.url === `file://${process.argv[1]}`) {
  const text = readme()
  if (process.argv.includes("--write")) writeFileSync(`${root}README.md`, text)
  else if (process.argv.includes("--check")) {
    const current = readFileSync(`${root}README.md`, "utf8")
    if (current !== text) {
      console.error("README.md is out of date: run node press/readme.mjs --write")
      process.exit(1)
    }
  } else process.stdout.write(text)
}
