// README.md, set from the same content as the sheets so the words and the
// pictures never disagree. GitHub sets the words in its own type (they
// reflow, search and follow the theme); the press prints the sheets.
//
//   node press/readme.mjs            print to stdout
//   node press/readme.mjs --write    write README.md
//   node press/readme.mjs --check    exit 1 if README.md is out of date
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { about, contact, datasheet, identity, principles, secret, stack, stamps } from "./content.mjs"
import { part } from "./lib/part.mjs"

const root = fileURLToPath(new URL("../", import.meta.url))
export const PRINTS = "https://raw.githubusercontent.com/KhaledSaeed18/KhaledSaeed18/prints"

const attr = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;")

/**
 * One sheet in both pulls. GitHub picks the source from its own theme
 * setting; the <img> is the dark pull, which carries its own paper, so it
 * reads on any page. Width only, never height (GitHub would box it).
 */
function pull(name, { width = "100%", alt = "", href, title } = {}) {
  const pic = `<picture><source media="(prefers-color-scheme: light)" srcset="${PRINTS}/${name}-light.svg"><img src="${PRINTS}/${name}-dark.svg" width="${width}" alt="${attr(alt)}"></picture>`
  return href ? `<a href="${attr(href)}"${title ? ` title="${attr(title)}"` : ""}>${pic}</a>` : pic
}

const pad = (n) => String(n).padStart(2, "0")

// the chip on sheet 02: one pin per tool, made up to a multiple of four
const chip = part(stack)
const ncComment =
  chip.nc === 1
    ? `pin ${chip.total} is not connected. it is reserved for whatever comes next.`
    : `pins ${chip.count + 1} to ${chip.total} are not connected. they are reserved for whatever comes next.`

const bits = [...secret].map((c) => c.charCodeAt(0).toString(2).padStart(8, "0")).join(" ")

const chipAlt = `Figure 1, the stack drawn as a ${chip.total}-pin chip, ${chip.name}. ${stack
  .map((l) => `${l.layer}: ${l.items.join(", ")}.`)
  .join(" ")}${chip.ncNote ? ` ${chip.ncNote}` : ""}`

